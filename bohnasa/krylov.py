"""Krylov-space construction and Krylov complexity."""

import logging

import numpy as np
import scipy.sparse as sp

from . import operators

logger = logging.getLogger(__name__)

MAX_REORTH_ITERATIONS = 20


def lanczos(sta, op, krylov_dim, beta_tol=1e-8):
    """Lanczos recursion with full reorthogonalization.

    Builds an orthonormal Krylov basis by repeated action of ``op`` on
    ``sta`` and returns the tridiagonal projection of ``op`` onto it.

    Parameters
    ----------
    sta : numpy.ndarray
        Start vector (any norm; it is normalized internally).
    op : callable
        Operator applied as ``op(vector)`` - e.g. an :class:`Operator`
        instance from ``bohnasa.operators``.
    krylov_dim : int
        Number of Lanczos steps requested.
    beta_tol : float, default 1e-8
        Norm of ``w`` below which the Krylov space is considered exhausted
        (happy breakdown) and recursion stops early.

    Returns
    -------
    v : numpy.ndarray of complex, shape (k + 1, len(sta))
        Orthonormal Krylov vectors as rows, ``k + 1`` being the number of
        steps actually performed (rows after a happy breakdown are removed).
    T_m : numpy.ndarray of complex, shape (k + 1, k + 1)
        Symmetric tridiagonal projection of ``op`` onto the Krylov basis.

    Raises
    ------
    RuntimeError
        If iterative reorthogonalization fails to converge within
        ``MAX_REORTH_ITERATIONS`` passes.

    Notes
    -----
    Eigenvalues of ``T_m`` approximate the extreme eigenvalues of ``op``
    already for ``krylov_dim`` far below the full Hilbert-space dimension.
    """

    v = np.zeros((krylov_dim + 1, sta.shape[0]), dtype=complex)
    T_m = np.zeros((krylov_dim + 1, krylov_dim + 1), dtype=complex)
    v[0] = sta / np.linalg.norm(sta)

    w_prime = op(v[0])

    alpha = np.vdot(w_prime, v[0, :])

    w = w_prime - alpha * v[0, :]

    T_m[0, 0] = alpha

    for j in range(1, krylov_dim + 1):

        beta = np.linalg.norm(w)
        if beta < beta_tol:

            # Happy breakdown: the Krylov space is exhausted.
            v_happy = v[0:j, :]
            T_m_happy = T_m[0:j, 0:j]

            return v_happy, T_m_happy

        v[j, :] = w / beta
        w_prime = op(v[j, :])
        alpha = np.vdot(w_prime, v[j, :])

        w = w_prime - alpha * v[j, :] - beta * v[j - 1, :]
        w = w - v.T @ (v.conj() @ w)

        for _ in range(MAX_REORTH_ITERATIONS):
            wn = w - v.T @ (v.conj() @ w)
            if np.linalg.norm(wn - w) < 1e-12:
                w = wn
                break
            logger.debug(
                "Lanczos reorthogonalization step %d at Krylov index %d, "
                "residual %g", _, j, np.linalg.norm(wn - w)
            )
            w = wn
        else:
            raise RuntimeError(
                f"Lanczos reorthogonalization did not converge within "
                f"{MAX_REORTH_ITERATIONS} iterations at Krylov index {j}"
            )

        T_m[j, j] = alpha
        T_m[j, j - 1] = beta
        T_m[j - 1, j] = beta

    return v, T_m


def krylov_complexity(fock, op, sta, numVec):
    """Krylov complexity operator for the evolution generated by ``op``.

    Runs ``lanczos`` on ``sta`` and returns the number operator
    ``diag(0, 1, 2, ...)`` of the Krylov basis, represented back in the
    physical ``fock`` basis. Its expectation value ``<K>`` measures how far
    the time-evolved state has spread through Krylov space.

    Parameters
    ----------
    fock : FixedNFockSpace
        Physical basis.
    op : callable
        Generator of the Krylov space (usually the Hamiltonian).
    sta : numpy.ndarray
        Start state in the physical basis.
    numVec : int
        Number of Krylov vectors requested.

    Returns
    -------
    Operator
        Krylov complexity operator in the physical basis.
    """
    v, T_m = lanczos(sta, op, numVec)

    krylov_op = operators.Operator(fock)
    krylov_op.matrix = sp.csr_matrix(v.conj().T @ np.diag(np.arange(v.shape[0])) @ v)
    return krylov_op


